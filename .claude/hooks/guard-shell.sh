#!/usr/bin/env bash
# Blocks shell commands that violate CLAUDE.md. Exit 2 = block, message to Claude via stderr.
source "$(dirname "$0")/lib.sh"

cmd=$(json_get tool_input.command)
[ -z "$cmd" ] && exit 0

# pattern<TAB>reason. Patterns are PCRE (grep -P), matched case-insensitively.
while IFS=$'\t' read -r pattern reason; do
  [ -z "$pattern" ] && continue
  if printf '%s' "$cmd" | grep -qiP -- "$pattern"; then
    block "Blocked by CLAUDE.md: $reason. Command: $cmd"
  fi
done <<'RULES'
git\s+push\b.*\s(-f\b|--force)	force push is forbidden
git\s+reset\s+--hard	history rewrite is forbidden
git\s+rebase	rebase is forbidden; commit directly to main
rm\s+-rf\s+(?!\.?/?target\b)	recursive delete outside target/ needs Vlad
Remove-Item.*-Recurse(?!.*\btarget\b)	recursive delete outside target/ needs Vlad
rmdir\s+/s	recursive delete needs Vlad
tauri\s+signer	updater keys are generated by Vlad only
cargo\s+publish	publishing needs Vlad
gh\s+release|git\s+tag\s+v	releases and version tags are created by Vlad only
curl\s.*\|\s*(sh|bash|powershell|iex)	piping downloads into a shell is forbidden
Invoke-Expression|\biex\b	iex is forbidden
RULES
exit 0
