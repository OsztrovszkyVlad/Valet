# Blocks shell commands that violate CLAUDE.md. Exit 2 = block, message to Claude via stderr.
$input_json = [Console]::In.ReadToEnd()
try { $data = $input_json | ConvertFrom-Json } catch { exit 0 }
$cmd = $data.tool_input.command
if (-not $cmd) { exit 0 }

$blocked = @(
  @{ pattern = 'git\s+push\s+(-f|--force)';            reason = 'force push is forbidden' },
  @{ pattern = 'git\s+reset\s+--hard';                  reason = 'history rewrite is forbidden' },
  @{ pattern = 'git\s+rebase';                          reason = 'rebase is forbidden; commit directly to main' },
  @{ pattern = 'rm\s+-rf\s+(?!\.?/?target\b)';          reason = 'recursive delete outside target/ needs Vlad' },
  @{ pattern = 'Remove-Item.*-Recurse(?!.*\btarget\b)'; reason = 'recursive delete outside target/ needs Vlad' },
  @{ pattern = 'rmdir\s+/s';                            reason = 'recursive delete needs Vlad' },
  @{ pattern = 'tauri\s+signer';                        reason = 'updater keys are generated by Vlad only' },
  @{ pattern = 'cargo\s+publish';                       reason = 'publishing needs Vlad' },
  @{ pattern = 'gh\s+release|git\s+tag\s+v';            reason = 'releases and version tags are created by Vlad only' },
  @{ pattern = 'curl\s.*\|\s*(sh|bash|powershell|iex)'; reason = 'piping downloads into a shell is forbidden' },
  @{ pattern = 'Invoke-Expression|\biex\b';             reason = 'iex is forbidden' }
)
foreach ($b in $blocked) {
  if ($cmd -match $b.pattern) {
    [Console]::Error.WriteLine("Blocked by CLAUDE.md: $($b.reason). Command: $cmd")
    exit 2
  }
}
exit 0
