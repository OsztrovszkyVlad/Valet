<#
.SYNOPSIS
Lays out Valet.exe, the filled AppxManifest.xml and the logos, and packs them
with makeappx into an unsigned Valet_<version>_x64.msix for the Microsoft
Store. The Store signs the package on submission.

.DESCRIPTION
- -Exe: the Valet.exe of `pnpm tauri build --no-bundle` (target\release\Valet.exe),
  built without the updater config (scripts/msix-manifest.mjs checks the
  build config before and the binary here).
- Writes <OutDir>\layout\ (Valet.exe, AppxManifest.xml, Assets\*.png) and
  <OutDir>\Valet_<version>_x64.msix. Fails if either already exists; nothing
  is overwritten.
- Identity and version: scripts/msix-manifest.mjs (environment variables
  VALET_MSIX_IDENTITY_NAME, VALET_MSIX_PUBLISHER,
  VALET_MSIX_PUBLISHER_DISPLAY_NAME; fake defaults with a warning unless
  -RequireIdentity). -AllowPrerelease accepts a x.y.z-pre version (dry runs).
- makeappx.exe: -MakeAppx, else the newest Windows SDK under
  KitsRoot10\bin\<version>\x64 (registry, then Program Files (x86)\Windows Kits\10),
  else PATH.
Under GitHub Actions writes msix=, manifest=, layout=, sdk_bin= (the folder
of makeappx.exe; signtool.exe is next to it) to $GITHUB_OUTPUT (plus the
values from msix-manifest.mjs) and emits ::notice title=msix pack:: lines.

.EXAMPLE
pwsh scripts/msix-pack.ps1 -Exe target\release\Valet.exe -OutDir $env:RUNNER_TEMP\msix -AllowPrerelease
#>
param(
    [Parameter(Mandatory = $true)][string]$Exe,
    [Parameter(Mandatory = $true)][string]$OutDir,
    [switch]$AllowPrerelease,
    [switch]$RequireIdentity,
    [string]$MakeAppx = ''
)

$ErrorActionPreference = 'Stop'
$InActions = ($env:GITHUB_ACTIONS -eq 'true')
$Repo = Split-Path -Parent $PSScriptRoot
$Icons = Join-Path $Repo 'apps\desktop\src-tauri\icons'
# Logos referenced by packaging/msix/AppxManifest.xml (generated by
# `pnpm tauri icon`, see docs/RELEASE.md section 7).
$Logos = @('Square44x44Logo.png', 'Square71x71Logo.png', 'Square150x150Logo.png', 'StoreLogo.png')

function Note([string]$Text) {
    Write-Host "msix-pack: $Text"
    if ($InActions) { Write-Host "::notice title=msix pack::$($Text -replace '%', '%25')" }
}

function Fail([string]$Text) {
    Write-Host "msix-pack: FAIL: $Text"
    if ($InActions) { Write-Host "::error title=msix pack::$($Text -replace '%', '%25')" }
    exit 1
}

function Add-Output([string]$Line) {
    if ($env:GITHUB_OUTPUT) { $Line | Out-File -FilePath $env:GITHUB_OUTPUT -Append -Encoding utf8 }
}

# Newest x64 copy of a Windows SDK tool, or $Override.
function Find-SdkTool([string]$Name, [string]$Override) {
    if ($Override) {
        if (Test-Path -LiteralPath $Override -PathType Leaf) { return (Resolve-Path -LiteralPath $Override).Path }
        Fail "$Name not found at $Override"
    }
    $roots = New-Object System.Collections.Generic.List[string]
    $reg = Get-ItemProperty -LiteralPath 'HKLM:\SOFTWARE\Microsoft\Windows Kits\Installed Roots' -Name KitsRoot10 -ErrorAction SilentlyContinue
    if ($null -ne $reg -and $reg.KitsRoot10) { $roots.Add($reg.KitsRoot10) }
    $roots.Add((Join-Path ${env:ProgramFiles(x86)} 'Windows Kits\10'))
    foreach ($root in $roots) {
        $bin = Join-Path $root 'bin'
        if (-not (Test-Path -LiteralPath $bin)) { continue }
        $versions = @(Get-ChildItem -LiteralPath $bin -Directory -ErrorAction SilentlyContinue |
                Where-Object { $_.Name -match '^\d+\.\d+\.\d+\.\d+$' } |
                Sort-Object -Property @{ Expression = { [version]$_.Name } } -Descending)
        foreach ($v in $versions) {
            $candidate = Join-Path $v.FullName "x64\$Name"
            if (Test-Path -LiteralPath $candidate -PathType Leaf) { return $candidate }
        }
        $flat = Join-Path $bin "x64\$Name"
        if (Test-Path -LiteralPath $flat -PathType Leaf) { return $flat }
    }
    $cmd = Get-Command $Name -ErrorAction SilentlyContinue
    if ($null -ne $cmd) { return $cmd.Source }
    Fail "$Name not found (Windows SDK); pass its path"
}

# --- Inputs ----------------------------------------------------------------------
if (-not (Test-Path -LiteralPath $Exe -PathType Leaf)) { Fail "no executable at $Exe" }
$Exe = (Resolve-Path -LiteralPath $Exe).Path
if (-not (Test-Path -LiteralPath $OutDir)) { $null = New-Item -ItemType Directory -Path $OutDir }
$OutDir = (Resolve-Path -LiteralPath $OutDir).Path
$Layout = Join-Path $OutDir 'layout'
if (Test-Path -LiteralPath $Layout) { Fail "$Layout already exists; use an empty -OutDir" }
foreach ($logo in $Logos) {
    if (-not (Test-Path -LiteralPath (Join-Path $Icons $logo) -PathType Leaf)) { Fail "missing logo $Icons\$logo" }
}
$conf = Get-Content -LiteralPath (Join-Path $Repo 'apps\desktop\src-tauri\tauri.conf.json') -Raw | ConvertFrom-Json
$appVersion = $conf.version
$Msix = Join-Path $OutDir "Valet_${appVersion}_x64.msix"
if (Test-Path -LiteralPath $Msix) { Fail "$Msix already exists; use an empty -OutDir" }

# --- Layout ------------------------------------------------------------------------
$null = New-Item -ItemType Directory -Path (Join-Path $Layout 'Assets')
Copy-Item -LiteralPath $Exe -Destination (Join-Path $Layout 'Valet.exe')
foreach ($logo in $Logos) {
    Copy-Item -LiteralPath (Join-Path $Icons $logo) -Destination (Join-Path $Layout "Assets\$logo")
}

$Manifest = Join-Path $Layout 'AppxManifest.xml'
$nodeArgs = @((Join-Path $Repo 'scripts\msix-manifest.mjs'), '--out', $Manifest, '--exe', (Join-Path $Layout 'Valet.exe'))
if ($AllowPrerelease) { $nodeArgs += '--allow-prerelease' }
if ($RequireIdentity) { $nodeArgs += '--require-identity' }
& node @nodeArgs
if ($LASTEXITCODE -ne 0) { Fail "msix-manifest.mjs exit code $LASTEXITCODE (see the msix error annotations)" }
if (-not (Test-Path -LiteralPath $Manifest -PathType Leaf)) { Fail "msix-manifest.mjs did not write $Manifest" }

[xml]$xml = Get-Content -LiteralPath $Manifest -Raw
$identity = $xml.DocumentElement.SelectSingleNode("*[local-name()='Identity']")
if ($null -eq $identity) { Fail "no Identity element in $Manifest" }
$exeMb = (Get-Item -LiteralPath $Exe).Length / 1MB
Note ("layout: Valet.exe {0:N2} MB, {1} logos; identity {2}, publisher {3}, package version {4} (app {5})" -f `
        $exeMb, $Logos.Count, $identity.GetAttribute('Name'), $identity.GetAttribute('Publisher'), $identity.GetAttribute('Version'), $appVersion)

# --- makeappx ------------------------------------------------------------------------
$makeappxPath = Find-SdkTool 'makeappx.exe' $MakeAppx
$sdkBin = Split-Path -Parent $makeappxPath
$sw = [Diagnostics.Stopwatch]::StartNew()
$out = @(& $makeappxPath pack /d $Layout /p $Msix 2>&1 | ForEach-Object { "$_" })
$code = $LASTEXITCODE
$out | ForEach-Object { Write-Host $_ }
if ($code -ne 0 -or -not (Test-Path -LiteralPath $Msix -PathType Leaf)) {
    $errors = @($out | Where-Object { $_ -match 'error' } | Select-Object -First 5)
    Fail "makeappx pack exit code $code ($makeappxPath): $($errors -join ' | ')"
}
$warnings = @($out | Where-Object { $_ -match 'warning' } | Select-Object -First 5)
if ($warnings.Count -gt 0) { Note "makeappx warnings: $($warnings -join ' | ')" }

$f = Get-Item -LiteralPath $Msix
$sha = (Get-FileHash -LiteralPath $Msix -Algorithm SHA256).Hash.ToLower()
Note ("packed {0} in {1:N1} s with {2}: {3:N2} MB ({4} bytes), unsigned, sha256 {5}" -f `
        $f.Name, $sw.Elapsed.TotalSeconds, $makeappxPath, ($f.Length / 1MB), $f.Length, $sha)

Add-Output "msix=$Msix"
Add-Output "manifest=$Manifest"
Add-Output "layout=$Layout"
Add-Output "sdk_bin=$sdkBin"
exit 0
